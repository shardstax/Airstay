-- Idempotency keys for booking creation (POST /bookings/init with an Idempotency-Key header).
--
-- Why PostgreSQL and not Redis: the key must be saved in the SAME transaction as the booking. Then either both exist
-- or neither does, so a crash can never leave a booking without its key (a retry would book twice) or a key without a
-- booking. Redis cannot take part in that transaction.
--
-- A key belongs to one user. request_hash fingerprints the request so the same key cannot be reused for a different
-- booking. booking_id is NULL only inside the transaction that claimed the key; it is set before that commits.
CREATE TABLE idempotency_key (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    idempotency_key VARCHAR(100) NOT NULL,
    request_hash    VARCHAR(64)  NOT NULL,
    booking_id      BIGINT       REFERENCES booking (id) ON DELETE CASCADE,
    created_at      TIMESTAMP(6) NOT NULL,
    CONSTRAINT unique_user_idempotency_key UNIQUE (user_id, idempotency_key)
);

-- Old keys are deleted by a scheduled job; this index makes that delete cheap.
CREATE INDEX idx_idempotency_key_created_at ON idempotency_key (created_at);
