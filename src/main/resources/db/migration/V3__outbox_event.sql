-- Transactional outbox: events that must reach other systems (Kafka) are saved here IN THE SAME TRANSACTION as the
-- business change that caused them. Either both are committed or neither is, so an event can never be lost or
-- invented, whatever happens to Kafka, the network or the process at that moment.
--
-- A relay (OutboxRelay) reads unpublished rows in id order, publishes them and sets published_at. Delivery is
-- at-least-once: a crash between publishing and marking publishes the row again, so consumers must be idempotent
-- (every event carries a unique event_id).
CREATE TABLE outbox_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     UUID         NOT NULL UNIQUE,
    topic        VARCHAR(100) NOT NULL,
    event_key    VARCHAR(100) NOT NULL,   -- Kafka message key: the booking id, so one booking's events stay in order
    event_type   VARCHAR(60)  NOT NULL,
    payload      TEXT         NOT NULL,   -- JSON
    created_at   TIMESTAMP(6) NOT NULL,
    published_at TIMESTAMP(6)
);

-- The relay only ever looks at unpublished rows, so index just those: it stays tiny however many events exist.
CREATE INDEX idx_outbox_unpublished ON outbox_event (id) WHERE published_at IS NULL;
