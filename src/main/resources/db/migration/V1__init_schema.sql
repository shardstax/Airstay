-- AirStay initial schema. Hibernate runs with ddl-auto=validate, so this file is the source of truth.

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password      VARCHAR(255) NOT NULL,
    name          VARCHAR(255),
    date_of_birth DATE,
    gender        VARCHAR(16) CHECK (gender IN ('MALE', 'FEMALE', 'OTHER'))
);

CREATE TABLE app_user_roles (
    user_id BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    role    VARCHAR(32) NOT NULL CHECK (role IN ('GUEST', 'HOTEL_MANAGER')),
    PRIMARY KEY (user_id, role)
);

CREATE TABLE hotel (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL,
    city         VARCHAR(255),
    photos       TEXT[],
    amenities    TEXT[],
    address      VARCHAR(255),
    phone_number VARCHAR(255),
    email        VARCHAR(255),
    location     VARCHAR(255),
    active       BOOLEAN      NOT NULL,
    owner_id     BIGINT       NOT NULL REFERENCES app_user (id),
    created_at   TIMESTAMP(6),
    updated_at   TIMESTAMP(6)
);
CREATE INDEX idx_hotel_owner ON hotel (owner_id);
CREATE INDEX idx_hotel_city_active ON hotel (city, active);

CREATE TABLE room (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id    BIGINT         NOT NULL REFERENCES hotel (id),
    type        VARCHAR(255)   NOT NULL,
    base_price  NUMERIC(10, 2) NOT NULL CHECK (base_price > 0),
    photos      TEXT[],
    amenities   TEXT[],
    total_count INTEGER        NOT NULL CHECK (total_count > 0),
    capacity    INTEGER        NOT NULL CHECK (capacity > 0),
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6)
);
CREATE INDEX idx_room_hotel ON room (hotel_id);

-- One row per room per night. The CHECK constraint is the last line of defence against overbooking.
CREATE TABLE inventory (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id       BIGINT         NOT NULL REFERENCES hotel (id),
    room_id        BIGINT         NOT NULL REFERENCES room (id),
    date           DATE           NOT NULL,
    booked_count   INTEGER        NOT NULL DEFAULT 0,
    reserved_count INTEGER        NOT NULL DEFAULT 0,
    total_count    INTEGER        NOT NULL,
    surge_factor   NUMERIC(5, 2)  NOT NULL,
    price          NUMERIC(10, 2) NOT NULL,
    city           VARCHAR(255)   NOT NULL,
    closed         BOOLEAN        NOT NULL,
    created_at     TIMESTAMP(6),
    updated_at     TIMESTAMP(6),
    CONSTRAINT unique_hotel_room_date UNIQUE (hotel_id, room_id, date),
    CONSTRAINT chk_inventory_counts CHECK (
        booked_count >= 0 AND reserved_count >= 0 AND booked_count + reserved_count <= total_count
    )
);
CREATE INDEX idx_inventory_room_date ON inventory (room_id, date);
CREATE INDEX idx_inventory_city_date ON inventory (city, date);

CREATE TABLE hotel_min_price (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id   BIGINT         NOT NULL REFERENCES hotel (id),
    date       DATE           NOT NULL,
    price      NUMERIC(10, 2) NOT NULL,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    CONSTRAINT unique_hotel_min_price_date UNIQUE (hotel_id, date)
);

CREATE TABLE guest (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       REFERENCES app_user (id),
    name          VARCHAR(255) NOT NULL,
    gender        VARCHAR(16) CHECK (gender IN ('MALE', 'FEMALE', 'OTHER')),
    date_of_birth DATE,
    created_at    TIMESTAMP(6),
    updated_at    TIMESTAMP(6)
);
CREATE INDEX idx_guest_user ON guest (user_id);

CREATE TABLE booking (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id           BIGINT         NOT NULL REFERENCES hotel (id),
    room_id            BIGINT         NOT NULL REFERENCES room (id),
    user_id            BIGINT         NOT NULL REFERENCES app_user (id),
    rooms_count        INTEGER        NOT NULL CHECK (rooms_count > 0),
    check_in_date      DATE           NOT NULL,
    check_out_date     DATE           NOT NULL,
    booking_status     VARCHAR(32)    NOT NULL CHECK (booking_status IN
        ('RESERVED', 'GUESTS_ADDED', 'PAYMENTS_PENDING', 'CONFIRMED', 'CANCELLED', 'EXPIRED')),
    amount             NUMERIC(10, 2) NOT NULL,
    payment_session_id VARCHAR(255) UNIQUE,
    expires_at         TIMESTAMP(6),
    created_at         TIMESTAMP(6),
    updated_at         TIMESTAMP(6),
    CONSTRAINT chk_booking_dates CHECK (check_out_date > check_in_date)
);
CREATE INDEX idx_booking_user ON booking (user_id);
CREATE INDEX idx_booking_hotel_created ON booking (hotel_id, created_at);
CREATE INDEX idx_booking_status_expires ON booking (booking_status, expires_at);

CREATE TABLE booking_guest (
    booking_id BIGINT NOT NULL REFERENCES booking (id) ON DELETE CASCADE,
    guest_id   BIGINT NOT NULL REFERENCES guest (id),
    PRIMARY KEY (booking_id, guest_id)
);
